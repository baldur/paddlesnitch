import Foundation

/// Generates `PaddleAPI/Generated/` from `mobile/contract/api/`: one Swift file
/// per schema, plus `Procedures.swift`.
///
/// The contract's rules (mobile/contract/README.md) shape the output:
/// unknown fields are ignored (Codable's default), unknown enum values and
/// union kinds decode to `.unknown`, and `oneOf` unions are discriminated by
/// `kind`. The two shapes the README maps by hand, `[lat, lng]` tuples and
/// `Seat`, are written by hand in PaddleAPI.
public enum ModelsGenerator {
    public enum Failure: Error, Equatable, CustomStringConvertible {
        case unsupported(type: String, reason: String)
        case badName(type: String, name: String)
        case unknownType(String)

        public var description: String {
            switch self {
            case .unsupported(let type, let reason): "\(type): unsupported schema: \(reason)"
            case .badName(let type, let name): "\(type): \(name) doesn't make a Swift identifier"
            case .unknownType(let name): "procedures.json or rest.json names \(name), which has no schema"
            }
        }
    }

    /// Schemas written by hand in PaddleAPI instead of generated.
    static let handWritten: Set<String> = ["Seat"]

    /// Readable case names where the raw values aren't identifiers.
    static let caseNames: [String: [String: String]] = [
        "BoatClass": [
            "1X": "single", "2X": "double", "4X+": "coxedQuad", "4X-": "quad",
            "2-": "pair", "4+": "coxedFour", "4-": "four", "8+": "eight",
        ]
    ]

    static let header = """
        // Generated by contract-gen from mobile/contract/api/. Don't edit: run
        // `make generate` in mobile/ios after the contract changes.
        // swift-format-ignore-file

        import Foundation


        """

    /// `schemas` maps a file name (`BoatClass.schema.json`) to its contents.
    /// Returns file name → Swift source.
    public static func generate(schemas: [String: Data], procedures: Data, rest: Data? = nil) throws
        -> [String: String]
    {
        var files: [String: String] = [:]
        var known: Set<String> = []
        for (file, data) in schemas {
            let name = String(file.dropLast(".schema.json".count))
            known.insert(name)
            guard !handWritten.contains(name) else { continue }
            let schema = try JSONDecoder().decode(JSON.self, from: data)
            files["\(name).swift"] = header + (try declaration(name: name, schema: schema, owner: name))
        }
        files["Procedures.swift"] = try proceduresFile(procedures, known: known)
        if let rest {
            files["Endpoints.swift"] = try endpointsFile(rest, known: known)
        }
        return files
    }

    // MARK: Declarations

    private static func declaration(name: String, schema: JSON, owner: String) throws -> String {
        if let variants = schema["oneOf"]?.array {
            return try union(name: name, variants: variants, owner: owner)
        }
        if let values = schema["enum"]?.array {
            return try stringEnum(name: name, values: values.compactMap(\.string), owner: owner)
        }
        if schema["type"]?.string == "object" {
            return try structure(name: name, schema: schema, owner: owner)
        }
        throw Failure.unsupported(type: owner, reason: "\(name) is neither an object, an enum nor a oneOf")
    }

    private static func structure(name: String, schema: JSON, owner: String, skipping skipped: Set<String> = [])
        throws -> String
    {
        let required = Set(schema["required"]?.array?.compactMap(\.string) ?? [])
        let properties = (schema["properties"]?.object ?? [:]).filter { !skipped.contains($0.key) }
        var fields: [(name: String, type: String)] = []
        var nested: [String] = []
        for (key, property) in properties.sorted(by: { $0.key < $1.key }) {
            guard Naming.isIdentifier(key) else { throw Failure.badName(type: owner, name: key) }
            var ref = try typeRef(property, name: nestedName(for: key), owner: owner, nested: &nested)
            if !required.contains(key) { ref.optional = true }
            fields.append((Naming.escaped(key), ref.optional ? ref.swift + "?" : ref.swift))
        }
        var out = "public struct \(name): Codable, Hashable, Sendable {\n"
        out += fields.map { "    public var \($0.name): \($0.type)\n" }.joined()
        if !fields.isEmpty {
            let parameters = fields.map { "\($0.name): \($0.type)\($0.type.hasSuffix("?") ? " = nil" : "")" }
            let oneLine = "    public init(\(parameters.joined(separator: ", "))) {\n"
            out +=
                "\n"
                + (oneLine.count <= 110
                    ? oneLine
                    : "    public init(\n" + parameters.map { "        \($0)" }.joined(separator: ",\n") + "\n    ) {\n")
            out += fields.map { "        self.\($0.name) = \($0.name)\n" }.joined()
            out += "    }\n"
        } else {
            out += "\n    public init() {}\n"
        }
        for declaration in nested {
            out += "\n" + indented(declaration)
        }
        return out + "}\n"
    }

    private static func stringEnum(name: String, values: [String], owner: String) throws -> String {
        let overrides = caseNames[name] ?? [:]
        let cases = try values.map { value in
            let swift = overrides[value] ?? Naming.lowerCamel(value)
            guard Naming.isIdentifier(swift.trimmingCharacters(in: ["`"])) else {
                throw Failure.badName(type: owner, name: value)
            }
            return (swift: swift, raw: value)
        }
        var out = "public enum \(name): Codable, Hashable, Sendable {\n"
        out += cases.map { "    case \($0.swift)\n" }.joined()
        out += "    /// A value this version of the app doesn't know yet.\n"
        out += "    case unknown(String)\n\n"
        out += "    /// Every value this version of the app knows.\n"
        out += "    public static let known: [\(name)] = [\(cases.map { ".\($0.swift)" }.joined(separator: ", "))]\n\n"
        out += "    public init(rawValue: String) {\n        switch rawValue {\n"
        out += cases.map { "        case \(literal($0.raw)): self = .\($0.swift)\n" }.joined()
        out += "        default: self = .unknown(rawValue)\n        }\n    }\n\n"
        out += "    public var rawValue: String {\n        switch self {\n"
        out += cases.map { "        case .\($0.swift): \(literal($0.raw))\n" }.joined()
        out += "        case .unknown(let rawValue): rawValue\n        }\n    }\n\n"
        out += """
                public init(from decoder: any Decoder) throws {
                    self.init(rawValue: try decoder.singleValueContainer().decode(String.self))
                }

                public func encode(to encoder: any Encoder) throws {
                    var container = encoder.singleValueContainer()
                    try container.encode(rawValue)
                }
            }

            """
        return out
    }

    private static func union(name: String, variants: [JSON], owner: String) throws -> String {
        let parsed = try variants.map { variant in
            guard variant["type"]?.string == "object", let kind = variant["properties"]?["kind"]?["const"]?.string
            else { throw Failure.unsupported(type: owner, reason: "a oneOf variant of \(name) has no kind const") }
            let caseName = Naming.lowerCamel(kind)
            let structName = Naming.upperCamel(kind)
            return (
                kind: kind, caseName: caseName, structName: structName,
                declaration: try structure(name: structName, schema: variant, owner: owner, skipping: ["kind"])
            )
        }
        var out = "public enum \(name): Codable, Hashable, Sendable {\n"
        out += parsed.map { "    case \($0.caseName)(\($0.structName))\n" }.joined()
        out += "    /// A kind this version of the app doesn't know yet.\n"
        out += "    case unknown(kind: String)\n\n"
        out += "    public var kind: String {\n        switch self {\n"
        out += parsed.map { "        case .\($0.caseName): \(literal($0.kind))\n" }.joined()
        out += "        case .unknown(let kind): kind\n        }\n    }\n\n"
        out += "    private enum KindKey: String, CodingKey {\n        case kind\n    }\n\n"
        out += "    public init(from decoder: any Decoder) throws {\n"
        out += "        let kind = try decoder.container(keyedBy: KindKey.self).decode(String.self, forKey: .kind)\n"
        out += "        switch kind {\n"
        out += parsed.map {
            "        case \(literal($0.kind)): self = .\($0.caseName)(try \($0.structName)(from: decoder))\n"
        }
        .joined()
        out += "        default: self = .unknown(kind: kind)\n        }\n    }\n\n"
        out += "    public func encode(to encoder: any Encoder) throws {\n        switch self {\n"
        out += parsed.map { "        case .\($0.caseName)(let value): try value.encode(to: encoder)\n" }.joined()
        out += "        case .unknown: break\n        }\n"
        out += "        var container = encoder.container(keyedBy: KindKey.self)\n"
        out += "        try container.encode(kind, forKey: .kind)\n    }\n"
        for variant in parsed {
            out += "\n" + indented(variant.declaration)
        }
        return out + "}\n"
    }

    // MARK: Types

    struct TypeRef {
        var swift: String
        var optional = false
    }

    private static func typeRef(_ schema: JSON, name: String, owner: String, nested: inout [String]) throws -> TypeRef {
        if let ref = schema["$ref"]?.string {
            return TypeRef(swift: String(ref.dropLast(".schema.json".count)))
        }
        if let all = schema["allOf"]?.array, all.count == 1 {
            return try typeRef(all[0], name: name, owner: owner, nested: &nested)
        }
        if let any = schema["anyOf"]?.array {
            let nonNull = any.filter { $0["type"]?.string != "null" }
            guard nonNull.count == 1, nonNull.count < any.count else {
                throw Failure.unsupported(type: owner, reason: "\(name): anyOf other than T | null")
            }
            var ref = try typeRef(nonNull[0], name: name, owner: owner, nested: &nested)
            ref.optional = true
            return ref
        }
        if let types = schema["type"]?.array?.compactMap(\.string) {
            let nonNull = types.filter { $0 != "null" }
            guard nonNull.count == 1 else {
                throw Failure.unsupported(type: owner, reason: "\(name): type union \(types)")
            }
            var single = schema.object ?? [:]
            single["type"] = .string(nonNull[0])
            var ref = try typeRef(.object(single), name: name, owner: owner, nested: &nested)
            ref.optional = types.contains("null")
            return ref
        }
        return try singleType(schema, name: name, owner: owner, nested: &nested)
    }

    /// A schema with one `type`.
    private static func singleType(_ schema: JSON, name: String, owner: String, nested: inout [String]) throws
        -> TypeRef
    {
        switch schema["type"]?.string {
        case "string":
            if let values = schema["enum"]?.array {
                nested.append(try stringEnum(name: name, values: values.compactMap(\.string), owner: owner))
                return TypeRef(swift: name)
            }
            return TypeRef(swift: schema["format"]?.string == "date-time" ? "Date" : "String")
        case "number": return TypeRef(swift: "Double")
        case "integer": return TypeRef(swift: "Int")
        case "boolean": return TypeRef(swift: "Bool")
        case "object":
            nested.append(try structure(name: name, schema: schema, owner: owner))
            return TypeRef(swift: name)
        case "array":
            return try arrayType(schema, name: name, owner: owner, nested: &nested)
        default:
            throw Failure.unsupported(type: owner, reason: "\(name): no type")
        }
    }

    private static func arrayType(_ schema: JSON, name: String, owner: String, nested: inout [String]) throws
        -> TypeRef
    {
        // A [lat, lng] tuple is one Coordinate, not an array of them.
        if let tuple = schema["items"]?.array {
            guard tuple.count == 2, tuple.allSatisfy({ $0["type"]?.string == "number" }) else {
                throw Failure.unsupported(type: owner, reason: "\(name): a tuple other than [lat, lng]")
            }
            return TypeRef(swift: "Coordinate")
        }
        guard let items = schema["items"] else {
            throw Failure.unsupported(type: owner, reason: "\(name): array without items")
        }
        let element = try typeRef(items, name: Naming.singular(name), owner: owner, nested: &nested)
        return TypeRef(swift: "[\(element.swift)\(element.optional ? "?" : "")]")
    }

    /// The name of a type nested for a property. `type` would clash with
    /// Swift's `.Type`, so it becomes `Kind`.
    private static func nestedName(for property: String) -> String {
        let name = Naming.upperCamel(property)
        return name == "Type" ? "Kind" : name
    }

    // MARK: Helpers

    private static func indented(_ text: String) -> String {
        text.split(separator: "\n", omittingEmptySubsequences: false)
            .map { $0.isEmpty ? "" : "    " + $0 }
            .joined(separator: "\n")
            .trimmingCharacters(in: .newlines) + "\n"
    }

    static func literal(_ value: String) -> String {
        "\"" + value.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"") + "\""
    }
}
