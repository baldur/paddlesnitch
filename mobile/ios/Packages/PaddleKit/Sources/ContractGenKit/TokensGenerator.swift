import Foundation

/// Generates `DesignSystem/Generated/Tokens.swift` from
/// `mobile/contract/tokens/tokens.json`.
public enum TokensGenerator {
    public struct Tokens: Decodable, Sendable {
        public var color: [String: String]
        public var radius: [String: Double]
        public var font: [String: String]
    }

    public enum Failure: Error, Equatable, CustomStringConvertible {
        case badHex(name: String, value: String)
        case badName(String)

        public var description: String {
            switch self {
            case .badHex(let name, let value): "color \(name): \(value) is not #rrggbb"
            case .badName(let name): "token name \(name) doesn't make a Swift identifier"
            }
        }
    }

    public static func generate(json: Data) throws -> String {
        let tokens = try JSONDecoder().decode(Tokens.self, from: json)
        var out = """
            // Generated by contract-gen from mobile/contract/tokens/tokens.json.
            // Don't edit: change packages/ui/src/tokens.css, run `pnpm mobile:contract`,
            // then `make generate` in mobile/ios.

            import SwiftUI

            /// The platform's colours. The theme is dark only.
            public enum Palette {

            """
        for (name, value) in tokens.color.sorted(by: { $0.key < $1.key }) {
            let hex = try parseHex(value, name: name)
            out += "    public static let \(try identifier(name)) = Color(hex: 0x\(hexString(hex)))\n"
        }
        out += """
            }

            /// Corner radii in points.
            public enum Radius {

            """
        for (name, value) in tokens.radius.sorted(by: { $0.key < $1.key }) {
            out += "    public static let \(try identifier(name)): CGFloat = \(number(value))\n"
        }
        out += """
            }

            /// Font family names. The app bundles the fonts itself.
            public enum FontFamily {

            """
        for (name, value) in tokens.font.sorted(by: { $0.key < $1.key }) {
            out += "    public static let \(try identifier(name)) = \(literal(value))\n"
        }
        out += "}\n"
        return out
    }

    /// `surface-2` → `surface2`, `primary-text` → `primaryText`.
    /// The launch screen's asset-catalog colour: the `bg` token, so the app
    /// opens on the same colour it draws.
    public static func launchBackground(json: Data) throws -> String {
        let tokens = try JSONDecoder().decode(Tokens.self, from: json)
        let hex = try parseHex(tokens.color["bg"] ?? "", name: "bg")
        func component(_ shift: UInt32) -> String {
            "0x" + String(format: "%02X", (hex >> shift) & 0xff)
        }
        return """
            {
              "colors" : [
                {
                  "color" : {
                    "color-space" : "srgb",
                    "components" : {
                      "alpha" : "1.000",
                      "blue" : "\(component(0))",
                      "green" : "\(component(8))",
                      "red" : "\(component(16))"
                    }
                  },
                  "idiom" : "universal"
                }
              ],
              "info" : {
                "author" : "contract-gen",
                "version" : 1
              }
            }

            """
    }

    static func identifier(_ name: String) throws -> String {
        let parts = name.split(separator: "-", omittingEmptySubsequences: false).map(String.init)
        guard let first = parts.first, first.first?.isLetter == true,
            parts.allSatisfy({ !$0.isEmpty && $0.allSatisfy { $0.isLetter || $0.isNumber } })
        else { throw Failure.badName(name) }
        return first + parts.dropFirst().map { $0.prefix(1).uppercased() + $0.dropFirst() }.joined()
    }

    static func parseHex(_ value: String, name: String) throws -> UInt32 {
        guard value.count == 7, value.first == "#", let hex = UInt32(value.dropFirst(), radix: 16)
        else { throw Failure.badHex(name: name, value: value) }
        return hex
    }

    private static func hexString(_ hex: UInt32) -> String {
        let digits = String(hex, radix: 16)
        return String(repeating: "0", count: 6 - digits.count) + digits
    }

    private static func number(_ value: Double) -> String {
        value == value.rounded() ? String(Int(value)) : String(value)
    }

    private static func literal(_ value: String) -> String {
        "\"" + value.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"") + "\""
    }
}
