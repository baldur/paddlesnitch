// Puts the WebAssembly build of the core into the server's code, as a
// TypeScript module (packages/timing/src/recorder-core-wasm.ts), so the site
// needs no build step, no asset path and no wasi-sdk: the module travels
// with the code that loads it.
//
//   node wasm/embed.mjs write build/recorder_core.wasm   write the module
//   node wasm/embed.mjs check                            is it up to date?
//   node wasm/embed.mjs same build/recorder_core.wasm    is it this build?
//
// The module carries a SHA-256 of the C sources it was built from. `check`
// needs no compiler, so every PR can run it: change the core and forget to
// rebuild, and it fails. `same` compares the bytes with a fresh build (CI,
// after `make wasm`).
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const CORE = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(CORE, '..', 'packages', 'timing', 'src', 'recorder-core-wasm.ts');
// Every file the wasm rule in the Makefile builds from.
const SOURCES = [
  'include/recorder_core.h', 'src/stroke.h', 'src/recorder_core.c', 'src/stroke.c',
  'src/recorder_replay.c', 'wasm/recorder_core_wasm.c',
];

function sourceHash() {
  const h = createHash('sha256');
  for (const f of SOURCES) h.update(`${f}\n`).update(readFileSync(join(CORE, f)));
  return h.digest('hex');
}

function version() {
  const m = /#define RC_VERSION "([^"]+)"/.exec(readFileSync(join(CORE, 'include/recorder_core.h'), 'utf8'));
  if (!m) throw new Error('no RC_VERSION in recorder_core.h');
  return m[1];
}

const embedded = () => {
  const ts = readFileSync(OUT, 'utf8');
  const field = (name) => new RegExp(`export const ${name} = '([^']*)'`).exec(ts)?.[1];
  return { sources: field('RC_SOURCES_SHA256'), version: field('RC_VERSION'), wasm: Buffer.from(field('RC_WASM_BASE64') ?? '', 'base64') };
};

const [cmd, wasmPath] = process.argv.slice(2);
if (cmd === 'write' && wasmPath) {
  const wasm = readFileSync(wasmPath);
  writeFileSync(OUT, `// GENERATED by recorder-core/wasm/embed.mjs: do not edit. Rebuild with
//   make -C recorder-core wasm WASI_SDK=… && node recorder-core/wasm/embed.mjs write recorder-core/build/recorder_core.wasm
// The recorder core (recorder-core/, C) built for WebAssembly: the one
// implementation of the motion metrics, which the server runs through
// ./cadence.ts. CI fails when the C sources change and this doesn't.
export const RC_VERSION = '${version()}'
export const RC_SOURCES_SHA256 = '${sourceHash()}'
export const RC_WASM_BASE64 = '${wasm.toString('base64')}'
`);
  console.log(`wrote ${OUT} (${wasm.length} bytes of wasm)`);
} else if (cmd === 'check') {
  const e = embedded();
  if (e.sources !== sourceHash() || e.version !== version()) {
    console.error(`${OUT} was built from other C sources: rebuild it (see its first lines).`);
    process.exit(1);
  }
  console.log('the embedded core matches the C sources');
} else if (cmd === 'same' && wasmPath) {
  if (!embedded().wasm.equals(readFileSync(wasmPath))) {
    console.error(`${wasmPath} differs from the module in ${OUT}: rebuild it (see its first lines).`);
    process.exit(1);
  }
  console.log('the embedded core is byte for byte this build');
} else {
  console.error('usage: node embed.mjs write CORE.wasm | check | same CORE.wasm');
  process.exit(2);
}
